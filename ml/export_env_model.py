"""Export the no-light occupancy MLP (seed 0) from its FP32 TFLite file to a C header.

Features: [T_z (degC), RH (%), d5_T (K over 5 min)] standardized with the training
split's mean and sample SD. Light is deliberately excluded: on a node that switches
its own luminaires, measured light is circular evidence (paper, Sec. VI).

Usage: python3 -I export_env_model.py <Occupancy-detection-data dir> <fp32.tflite> <out.h>
"""
import os, sys
import numpy as np, pandas as pd
os.environ["TF_CPP_MIN_LOG_LEVEL"] = "3"
import tensorflow as tf

data_dir, model_path, out_path = sys.argv[1:4]
FEATS = ["Temperature", "Humidity", "dT"]

tr = pd.read_csv(os.path.join(data_dir, "datatraining.txt"))
tr["date"] = pd.to_datetime(tr["date"]); tr = tr.sort_values("date")
tr["dT"] = tr["Temperature"].diff(5); tr = tr.dropna()
mu, sd = tr[FEATS].mean().values, tr[FEATS].std().values   # pandas std = sample SD (ddof=1)

it = tf.lite.Interpreter(model_path=model_path); it.allocate_tensors()
tensors = {t["name"]: t for t in it.get_tensor_details()}
mats = sorted([t for t in tensors.values() if len(t["shape"]) == 2 and t["shape"][0] > 1 and "MatMul" in t["name"] and ";" not in t["name"]],
              key=lambda t: -t["shape"][1])
biases = [t for t in tensors.values() if len(t["shape"]) == 1]
# Order layers as a chain: input width 3 -> 32 -> 16 -> 2 (TFLite weights are [out, in]).
chain, width = [], 3
while len(chain) < len(mats):
    nxt = [t for t in mats if t["shape"][1] == width and t not in chain][0]
    chain.append(nxt); width = nxt["shape"][0]
mats = chain
layers = []
for W in mats:
    out_n = W["shape"][0]
    b = [t for t in biases if t["shape"][0] == out_n][0]
    layers.append((it.get_tensor(W["index"]).astype(np.float32), it.get_tensor(b["index"]).astype(np.float32)))
shapes = [(w.shape, b.shape) for w, b in layers]
assert [s[0] for s in shapes] == [(32, 3), (16, 32), (2, 16)], shapes

def arr(name, a):
    flat = ", ".join(f"{float(v):.9e}f" for v in a.flatten())
    return f"static const float {name}[{a.size}] = {{{flat}}};\n"

with open(out_path, "w") as f:
    f.write("// AUTO-GENERATED by ml/export_env_model.py -- do not edit.\n")
    f.write(f"// Source model: {os.path.basename(model_path)}; features T, RH, d5_T.\n#pragma once\n")
    f.write(arr("PN_ENV_MU", mu.astype(np.float32)) + arr("PN_ENV_SD", sd.astype(np.float32)))
    for i, (w, b) in enumerate(layers):
        f.write(arr(f"PN_ENV_W{i}", w) + arr(f"PN_ENV_B{i}", b))
print("wrote", out_path, "mu", mu, "sd", sd)
